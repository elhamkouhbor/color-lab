// Post-build for GitHub Pages: SPA fallback (404.html), no Jekyll, an offline service worker that
// precaches every built file, and a public-output audit (no source maps, no stray files).
import { copyFileSync, writeFileSync, readdirSync, statSync, readFileSync } from "node:fs";
import { join, relative } from "node:path";
import { createHash } from "node:crypto";

const dir = process.argv[2] || "dist";
copyFileSync(join(dir, "index.html"), join(dir, "404.html"));
writeFileSync(join(dir, ".nojekyll"), "");

const files = [];
const walk = (d) => { for (const f of readdirSync(d)) { const p = join(d, f); if (statSync(p).isDirectory()) walk(p); else files.push(relative(dir, p).split("\\").join("/")); } };
walk(dir);
const bad = files.filter((f) => /\.map$|\.ts$|\.tsx$|^\.env/.test(f));
if (bad.length) { console.error("public audit failed:", bad); process.exit(1); }

const precache = files.filter((f) => f !== "404.html" && f !== ".nojekyll" && f !== "sw.js");
const hash = createHash("sha256");
for (const f of precache.sort()) hash.update(f).update(readFileSync(join(dir, f)));
const version = hash.digest("hex").slice(0, 12);
writeFileSync(join(dir, "sw.js"), `// Color Lab offline cache (generated by scripts/postbuild.mjs). Same-origin files only.
const CACHE = "color-lab-${version}";
const FILES = ${JSON.stringify(["./", ...precache.map((f) => "./" + f)])};
self.addEventListener("install", (e) => { e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting())); });
self.addEventListener("activate", (e) => { e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith("color-lab-") && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET" || new URL(req.url).origin !== location.origin) return;
  if (req.mode === "navigate") { e.respondWith(fetch(req).catch(() => caches.match("./index.html", { ignoreSearch: true }).then((r) => r || caches.match("./")))); return; }
  e.respondWith(caches.match(req).then((hit) => hit || fetch(req)));
});
`);
console.log(`postbuild: 404.html, .nojekyll, sw.js (${precache.length} files, cache ${version}) in ${dir}`);
